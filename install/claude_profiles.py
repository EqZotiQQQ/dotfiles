"""Claude Code profiles: one VS Code profile per Claude account.

Every profile gets its own CLAUDE_CONFIG_DIR, so each one keeps its own login
(.credentials.json, .claude.json). Everything else is shared: the config dir
only holds symlinks into ~/.claude. The VS Code profile gets the default
profile's settings plus CLAUDE_CONFIG_DIR, a symlink to its keybindings, and
the extensions from vscode_extensions.txt.
"""

import json
import logging
import pathlib
import shutil
import subprocess
import time

HOME = pathlib.Path.home()
CLAUDE_HOME = HOME / ".claude"
VSCODE_USER = HOME / ".config" / "Code" / "User"
EXTENSIONS_LIST = pathlib.Path(__file__).parent / "vscode_extensions.txt"

PROFILES = {
    "EqZotiQQQClaude": HOME / ".claude-eqzotiqqq",
    "PandaClaude": HOME / ".claude-panda",
}

SHARED = {
    "settings.json": None,
    "settings.local.json": None,
    "CLAUDE.md": None,
    "skills": "dir",
    "plugins": "dir",
    "projects": "dir",
    "file-history": "dir",
    "paste-cache": "dir",
    "downloads": "dir",
    "ide": "dir",
    "history.jsonl": "file",
}

# files starting with this are ours and get overwritten without a backup
GENERATED_MARKER = "// Generated by `dot "
SETTINGS_HEADER = (
    GENERATED_MARKER + "--setup-vscode-profiles` from the default profile settings.json.\n"
    "// Edit that file instead — this one is overwritten on every run.\n"
)


def link_config_dir(config_dir: pathlib.Path, apply: bool) -> int:
    failed = 0
    if apply:
        config_dir.mkdir(mode=0o700, parents=True, exist_ok=True)

    for name, kind in SHARED.items():
        src = CLAUDE_HOME / name
        dst = config_dir / name
        if dst.is_symlink() and dst.readlink() == src:
            continue
        if dst.exists() and not dst.is_symlink():
            logging.error(f"real {'dir' if dst.is_dir() else 'file'} in the way — merge it into {src} and remove: {dst}")
            failed += 1
            continue
        if not apply:
            logging.info(f"[dry-run] {dst} -> {src}")
            continue

        if kind == "dir":
            src.mkdir(parents=True, exist_ok=True)
        elif kind == "file":
            src.touch()
        elif not src.exists():
            logging.error(f"{src} is missing — run `dot -s -f` first")
            failed += 1
            continue

        if dst.is_symlink():
            dst.unlink()
        dst.symlink_to(src)
        logging.info(f"linked: {dst} -> {src}")
    return failed


def vscode_profiles() -> dict[str, pathlib.Path]:
    """VS Code keeps its profile registry in storage.json; profile dirs have random names."""
    try:
        storage = json.loads((VSCODE_USER / "globalStorage" / "storage.json").read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    return {
        profile["name"]: VSCODE_USER / "profiles" / profile["location"]
        for profile in storage.get("userDataProfiles", [])
        if isinstance(profile.get("location"), str)
    }


def create_vscode_profile(name: str, config_dir: pathlib.Path) -> pathlib.Path | None:
    # The CLI can't create a profile on its own (`--install-extension` fails with
    # "Profile not found"), only opening a window with --profile does. The folder
    # gets associated with the profile, so use the Claude config dir for it.
    logging.info(f"creating VS Code profile {name} — this opens a window")
    subprocess.run(["code", "--profile", name, "--new-window", str(config_dir)], check=False)
    for _ in range(30):  # VS Code writes storage.json with a delay
        if location := vscode_profiles().get(name):
            return location
        time.sleep(1)
    return None


def last_significant(text: str, end: int) -> int:
    """Index of the last character before `end` that is neither whitespace nor part of a JSONC comment."""
    last = -1
    in_string = False
    i = 0
    while i < end:
        c = text[i]
        if in_string:
            if c == "\\":
                i += 1
            elif c == '"':
                in_string = False
            last = i
        elif text.startswith("//", i):
            newline = text.find("\n", i)
            i = end if newline == -1 else newline
            continue
        elif text.startswith("/*", i):
            close = text.find("*/", i + 2)
            i = end if close == -1 else close + 2
            continue
        elif not c.isspace():
            in_string = c == '"'
            last = i
        i += 1
    return last


def profile_settings(default_text: str, config_dir: pathlib.Path) -> str:
    """Default settings with CLAUDE_CONFIG_DIR appended, keeping the comments of the original."""
    if not default_text.strip():
        default_text = "{}"
    extra = {
        "claudeCode.environmentVariables": [{"name": "CLAUDE_CONFIG_DIR", "value": str(config_dir)}],
        "terminal.integrated.env.linux": {"CLAUDE_CONFIG_DIR": str(config_dir)},
    }
    entries = ",\n".join(f"    {json.dumps(key)}: {json.dumps(value)}" for key, value in extra.items())

    close = last_significant(default_text, len(default_text))
    if close < 0 or default_text[close] != "}":
        raise ValueError("default settings.json is not a JSON object")
    last = last_significant(default_text, close)
    separator = "" if default_text[last] in "{," else ","
    # appended last, so these win over the same keys in the default settings
    return (
        SETTINGS_HEADER
        + default_text[: last + 1]
        + separator
        + default_text[last + 1 : close].rstrip()
        + "\n"
        + entries
        + "\n}\n"
    )


def write_settings(path: pathlib.Path, content: str, apply: bool) -> None:
    current = path.read_text() if path.exists() else None
    if current == content:
        return
    if not apply:
        logging.info(f"[dry-run] write {path}")
        return

    path.parent.mkdir(parents=True, exist_ok=True)
    if current is not None and not current.startswith(GENERATED_MARKER):
        backup = path.with_name(path.name + ".bak")
        shutil.copy2(path, backup)
        logging.info(f"backup of hand-written settings: {backup}")
    path.write_text(content)
    logging.info(f"written: {path}")


def link_keybindings(location: pathlib.Path, apply: bool) -> int:
    # a profile has its own keybindings.json unless created with "use default"; share the default one
    src = VSCODE_USER / "keybindings.json"
    dst = location / "keybindings.json"
    if dst.is_symlink() and dst.readlink() == src:
        return 0
    if dst.exists() and not dst.is_symlink():
        logging.error(f"real file in the way — merge it into {src} and remove: {dst}")
        return 1
    if not apply:
        logging.info(f"[dry-run] {dst} -> {src}")
        return 0
    if dst.is_symlink():
        dst.unlink()
    dst.symlink_to(src)
    logging.info(f"linked: {dst} -> {src}")
    return 0


def wanted_extensions() -> list[str]:
    if not EXTENSIONS_LIST.exists():
        return []
    lines = (line.strip() for line in EXTENSIONS_LIST.read_text().splitlines())
    return [line for line in lines if line and not line.startswith("#")]


def install_extensions(profile: str | None, apply: bool) -> int:
    profile_args = ["--profile", profile] if profile else []
    listed = subprocess.run(["code", "--list-extensions", *profile_args], capture_output=True, text=True)
    if listed.returncode != 0:
        logging.error(f"code --list-extensions failed for {profile or 'default'}: {listed.stderr.strip()}")
        return 1
    installed = {line.strip().lower() for line in listed.stdout.splitlines()}

    failed = 0
    for extension in wanted_extensions():
        if extension.lower() in installed:
            continue
        if not apply:
            logging.info(f"[dry-run] install {extension} -> {profile or 'default'}")
            continue
        result = subprocess.run(
            ["code", "--install-extension", extension, *profile_args], capture_output=True, text=True
        )
        if result.returncode != 0:
            logging.error(f"failed to install {extension} -> {profile or 'default'}: {result.stderr.strip()}")
            failed += 1
        else:
            logging.info(f"installed: {extension} -> {profile or 'default'}")
    return failed


def setup_profiles(apply: bool) -> int:
    failed = 0
    for config_dir in PROFILES.values():
        failed += link_config_dir(config_dir, apply)

    if shutil.which("code") is None:
        logging.error("VS Code CLI `code` not found — VS Code profiles skipped")
        return failed + 1

    default_settings = VSCODE_USER / "settings.json"
    default_text = default_settings.read_text() if default_settings.exists() else ""
    failed += install_extensions(None, apply)

    existing = vscode_profiles()
    for name, config_dir in PROFILES.items():
        location = existing.get(name)
        if location is None:
            if not apply:
                logging.info(f"[dry-run] create VS Code profile {name}")
                continue
            location = create_vscode_profile(name, config_dir)
            if location is None:
                logging.error(f"VS Code profile {name} did not show up — create it in VS Code and re-run")
                failed += 1
                continue

        try:
            write_settings(location / "settings.json", profile_settings(default_text, config_dir), apply)
        except ValueError as e:
            logging.error(f"{default_settings}: {e}")
            failed += 1
        failed += link_keybindings(location, apply)
        failed += install_extensions(name, apply)

    if not apply:
        print("\nDry run complete — use -f to set up profiles.")
    return 1 if failed else 0
